import { execFileSync } from 'node:child_process';
import { readFileSync } from 'node:fs';
import { createRequire } from 'node:module';
const ids = JSON.parse(readFileSync(process.argv[2], 'utf8'));
const { chromium } = createRequire(process.argv[3] + '/apps/storefront/package.json')('playwright');
const sql = (q) => execFileSync(process.env.PSQL || 'C:/Program Files/PostgreSQL/17/bin/psql.exe', ['-U', 'naro_admin', '-h', 'localhost', '-d', 'naro_fashion', '-qAt', '-c', `SET search_path TO it_quote; ${q}`], { env: { ...process.env, PGPASSWORD: 'Admin123' }, encoding: 'utf8' }).trim();
sql(`UPDATE "Product" SET "rentalPricePerDay" = 250, "rentalDepositAmount" = 50, "rentalDownPaymentPct" = 25 WHERE id = '${ids.gown.id}'`);
const iso = (d) => new Date(Date.now() + d * 86400000).toISOString().slice(0, 10);
const b = await chromium.launch();
const p = await (await b.newContext()).newPage();
await p.goto('http://localhost:3101/rentals/it-gown', { waitUntil: 'networkidle', timeout: 180000 });
const d = p.locator('input[type="date"]');
await d.nth(0).fill(iso(250)); await d.nth(1).fill(iso(252));
await p.getByTestId('rental-available').waitFor({ timeout: 60000 });
const box = (await p.getByTestId('rental-price-breakdown').innerText()).replace(/\s+/g, ' ');
const dp = await p.getByTestId('rental-down-payment').innerText();
const note = await p.getByTestId('rental-payment-note').innerText();
await b.close();
sql(`UPDATE "Product" SET "rentalPricePerDay" = 140000, "rentalDepositAmount" = 350000, "rentalDownPaymentPct" = NULL WHERE id = '${ids.gown.id}'`);
const ok = /TSh\s*63\b/.test(dp) && /237/.test(box) && /300/.test(box) && /TSh\s*63\b/.test(note);
console.log(ok ? '  ✔' : '  ✖', 'fractional fee on the page (trial with PR #12):', box, '| note:', note.slice(0, 90));
process.exit(ok ? 0 : 1);
